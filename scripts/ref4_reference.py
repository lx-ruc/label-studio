def main() -> None:
    spec = load_spec()
    rows = []
    for r in REF:
        fixed, problems = validate(r["tasks"], spec)
        if problems:
            print(f"[{r['id']}] {len(problems)} 个问题：")
            for p in problems:
                print("   ", p)
        else:
            print(f"[{r['id']}] 校验通过")
        rows.append({**{k: v for k, v in r.items() if k != "tasks"}, "tasks": fixed})

    OUT.write_text("\n".join(json.dumps(x, ensure_ascii=False) for x in rows) + "\n",
                   encoding="utf-8")
    print(f"\n写出 {OUT}（{len(rows)} 条 × 12 任务）")


if __name__ == "__main__":
    main()
